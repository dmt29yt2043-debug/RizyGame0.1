// ---------- состояние движущихся платформ во времени ----------
export function moverPos(m, t){
  const a = Math.sin((t / m.T + (m.ph || 0)) * Math.PI * 2);
  return { ox: (m.ax || 0) * a, oy: (m.ay || 0) * a };
}

// мир для физики: solids + plats (oneway и движущиеся — одним списком, движущиеся с dx/dy)
// + vines (уровень 2, лазание) — у уровня 1 level.vines нет, значит world.vines = [], поведение не меняется.
export function buildWorld(level){
  const solids = level.solids.map(r => ({ id: r.id, x0: r.x0, x1: r.x1, y0: r.y0, y1: r.y1 }));
  const plats = level.oneways.map(o => ({ id: o.id, x0: o.x0, x1: o.x1, y: o.y, dx: 0, dy: 0 }));
  const movers = level.movers.map(m => {
    const pl = { id: m.id, x0: m.x0, x1: m.x1, y: m.y, dx: 0, dy: 0, m };
    plats.push(pl);
    return pl;
  });
  const vines = (level.vines || []).map(v => ({ id: v.id, x0: v.x0, x1: v.x1, y0: v.y0, y1: v.y1, side: v.side, cx: (v.x0 + v.x1) / 2 }));
  const w = { solids, plats, movers, vines };
  setMovers(w, 0, true);
  return w;
}
export function setMovers(w, t, reset){
  for (const pl of w.movers){
    const { ox, oy } = moverPos(pl.m, t);
    const nx0 = pl.m.x0 + ox, ny = pl.m.y + oy;
    pl.dx = reset ? 0 : nx0 - pl.x0; pl.dy = reset ? 0 : ny - pl.y;
    pl.x0 = nx0; pl.x1 = nx0 + (pl.m.x1 - pl.m.x0); pl.y = ny;
  }
}

// позиция врага во времени (центр); dir — куда смотрит
export function enemyPos(e, t){
  if (e.type === "patrol"){
    const L = e.x1 - e.x0, per = 2 * L / e.v;
    let u = ((t + (e.t0 || 0)) % per + per) % per;
    const fwd = u < per / 2;
    const x = fwd ? e.x0 + u * e.v : e.x1 - (u - per / 2) * e.v;
    return { x, y: e.y + 0.08 * Math.sin(t * 5.2 + e.x0), dir: fwd ? 1 : -1 };
  }
  const w = (t / e.T) * Math.PI * 2;
  return { x: e.x + e.ax * Math.sin(w), y: e.y + e.ay * Math.sin(w * 2), dir: Math.cos(w) >= 0 ? 1 : -1 };
}
